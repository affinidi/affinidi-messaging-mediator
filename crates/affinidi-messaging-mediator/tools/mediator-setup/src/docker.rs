use std::path::{Path, PathBuf};

use crate::app::WizardConfig;
use crate::config_writer::{CONTAINER_CONFIG_DIR, CONTAINER_SECRETS_DIR};

const DEFAULT_PORT: u16 = 7037;

/// Generate `Dockerfile`, `Dockerfile.dockerignore` and `docker-compose.yml`
/// in `output_dir` (the directory holding `mediator.toml`), so
/// `docker compose up --build` run there brings up the mediator (plus a
/// bundled Redis unless the storage backend is Fjall).
///
/// - The image holds the binary only. The config directory — `mediator.toml`,
///   `did.jsonl`, `admin-monitor.json`, a `file://` secrets file — is
///   mounted at runtime (at [`CONTAINER_CONFIG_DIR`]), never `COPY`ed into an
///   image layer where anyone with the image could read the keys.
/// - The `-c` path is derived from the config file's name, so a config
///   written anywhere works.
/// - The build context is the workspace root; the ignore file sits next to
///   the Dockerfile (`Dockerfile.dockerignore`), so the repository's own
///   `.dockerignore` is never touched.
/// - An existing file with different contents is never overwritten: the new
///   one is written as `<name>.new` and a warning says so.
///
/// Returns the paths written.
pub fn generate_dockerfile(
    config: &WizardConfig,
    output_dir: &Path,
) -> anyhow::Result<Vec<PathBuf>> {
    let features = config.cargo_features();
    let features_flag = if config.needs_explicit_features() {
        format!(" --no-default-features --features {}", features.join(","))
    } else {
        String::new()
    };
    let port = listen_port(&config.listen_address).unwrap_or(DEFAULT_PORT);
    let config_name = Path::new(&config.config_path)
        .file_name()
        .map(|n| n.to_string_lossy().into_owned())
        .unwrap_or_else(|| "mediator.toml".into());

    let dockerfile = format!(
        r#"# Affinidi Messaging Mediator
# Generated by mediator-setup
#
# The image carries the mediator binary only. Its configuration and any
# key files are mounted at {CONTAINER_CONFIG_DIR} at runtime (see
# docker-compose.yml) — never copied into an image layer.

FROM rust:1.95-bookworm AS builder

WORKDIR /build
COPY . .

RUN cargo build --release --locked -p affinidi-messaging-mediator{features_flag}

FROM debian:bookworm-slim

RUN apt-get update && apt-get install -y ca-certificates && rm -rf /var/lib/apt/lists/*

COPY --from=builder /build/target/release/mediator /usr/local/bin/mediator

WORKDIR /etc/mediator

EXPOSE {port}

CMD ["mediator", "-c", "{CONTAINER_CONFIG_DIR}/{config_name}"]
"#
    );

    let dockerignore = r#"target/
.git/
*.md
.github/
.vscode/
.idea/
"#;

    // Build context: the workspace root, relative to the compose file.
    let output_abs = absolute(output_dir);
    let workspace = crate::install::find_workspace_root();
    let (context, dockerfile_in_context) = match &workspace {
        Some(root) => (
            relative_path(&output_abs, root),
            relative_path(root, &output_abs.join("Dockerfile")),
        ),
        None => (".".to_string(), "Dockerfile".to_string()),
    };

    // Runtime mounts: the config directory, plus a `file://` secrets file
    // that lives outside it.
    let mut volumes = vec![format!("      - ./:{CONTAINER_CONFIG_DIR}")];
    if let Some(host) = crate::config_writer::file_backend_host_path(config)
        && !host.starts_with(&output_abs)
        && let Some(name) = host.file_name()
    {
        volumes.push(format!(
            "      - {}:{CONTAINER_SECRETS_DIR}/{}",
            host.display(),
            name.to_string_lossy()
        ));
    }

    // Two compose templates: one for the Redis-backed deployment
    // (the historical default) and one for the Fjall-backed
    // single-node deployment. The Fjall template skips the bundled
    // Redis service entirely — Fjall's data lives on disk in a
    // mounted volume, so there's no second container to wire up.
    let compose = if config.storage_backend == crate::consts::STORAGE_BACKEND_FJALL {
        volumes.push("      - mediator-data:/etc/mediator/data".into());
        let volumes = volumes.join("\n");
        format!(
            r#"# Affinidi Messaging Mediator (Fjall single-node)
# Generated by mediator-setup — run `docker compose up --build` here.
#
# Embedded LSM-tree backend; no Redis sidecar. The mediator stores
# state in `/etc/mediator/data` inside the container, mounted from
# the named volume below so data survives `docker compose down`.
# This directory is mounted at {CONTAINER_CONFIG_DIR}: the config and
# keys stay on the host, out of the image.

services:
  mediator:
    build:
      context: {context}
      dockerfile: {dockerfile_in_context}
    image: affinidi-mediator
    volumes:
{volumes}
    ports:
      - "{port}:{port}"
    restart: unless-stopped

volumes:
  mediator-data:
"#
        )
    } else {
        let volumes = volumes.join("\n");
        format!(
            r#"# Affinidi Messaging Mediator + Redis
# Generated by mediator-setup — run `docker compose up --build` here.
#
# Self-contained stack: the mediator and a bundled Redis on a private
# network. The mediator's `database_url` from mediator.toml is overridden
# via the DATABASE_URL env var so the same image still works against an
# external Redis when run outside of compose. Redis is not exposed on the
# host — only the mediator port is published. This directory is mounted at
# {CONTAINER_CONFIG_DIR}: the config and keys stay on the host, out of the
# image.

services:
  redis:
    image: redis:7-alpine
    command: ["redis-server", "--appendonly", "yes"]
    volumes:
      - redis-data:/data
    healthcheck:
      test: ["CMD", "redis-cli", "ping"]
      interval: 5s
      timeout: 3s
      retries: 5
    restart: unless-stopped

  mediator:
    build:
      context: {context}
      dockerfile: {dockerfile_in_context}
    image: affinidi-mediator
    depends_on:
      redis:
        condition: service_healthy
    environment:
      DATABASE_URL: redis://redis:6379/
    volumes:
{volumes}
    ports:
      - "{port}:{port}"
    restart: unless-stopped

volumes:
  redis-data:
"#
        )
    };

    crate::secure_fs::create_private_dir_all(output_dir)?;
    let mut written = Vec::new();
    for (name, contents) in [
        ("Dockerfile", dockerfile.as_str()),
        ("Dockerfile.dockerignore", dockerignore),
        ("docker-compose.yml", compose.as_str()),
    ] {
        written.push(write_without_clobbering(&output_dir.join(name), contents)?);
    }

    out!("\nDocker files generated:");
    for path in &written {
        out!("  {}", path.display());
    }
    out!("\nTo bring up the stack, from {}:", output_dir.display());
    out!("  docker compose up --build");
    out!("\nMediator listens on http://localhost:{port}");
    if config.storage_backend != crate::consts::STORAGE_BACKEND_FJALL {
        out!("Redis is internal to the compose network and not exposed.");
    }
    if workspace.is_none() {
        err!(
            "  \x1b[33mNote:\x1b[0m no Cargo workspace found from the current directory; edit \
             `build.context` in docker-compose.yml to point at the mediator source tree."
        );
    }

    Ok(written)
}

/// Write `contents` to `path` unless a different file is already there, in
/// which case write `<path>.new` and warn. Returns the path written.
fn write_without_clobbering(path: &Path, contents: &str) -> anyhow::Result<PathBuf> {
    match std::fs::read_to_string(path) {
        Ok(existing) if existing == contents => Ok(path.to_path_buf()),
        Ok(_) => {
            let mut name = path.file_name().unwrap_or_default().to_os_string();
            name.push(".new");
            let alt = path.with_file_name(name);
            crate::secure_fs::write_public(&alt, contents)?;
            err!(
                "  \x1b[33mWarning:\x1b[0m {} already exists and differs; not overwriting it. \
                 The generated version is {} — compare and merge by hand.",
                path.display(),
                alt.display()
            );
            Ok(alt)
        }
        Err(_) => {
            crate::secure_fs::write_public(path, contents)?;
            Ok(path.to_path_buf())
        }
    }
}

fn absolute(path: &Path) -> PathBuf {
    if path.is_absolute() {
        path.to_path_buf()
    } else {
        std::env::current_dir()
            .map(|cwd| cwd.join(path))
            .unwrap_or_else(|_| path.to_path_buf())
    }
}

/// `to` relative to the directory `from` (both absolute), with `..` steps.
fn relative_path(from: &Path, to: &Path) -> String {
    let from: Vec<_> = from.components().collect();
    let to_c: Vec<_> = to.components().collect();
    let common = from.iter().zip(&to_c).take_while(|(a, b)| a == b).count();
    let mut rel = PathBuf::new();
    for _ in common..from.len() {
        rel.push("..");
    }
    for c in &to_c[common..] {
        rel.push(c.as_os_str());
    }
    if rel.as_os_str().is_empty() {
        ".".into()
    } else {
        rel.to_string_lossy().into_owned()
    }
}
/// Extract the TCP port from a `host:port` listen address. Returns
/// `None` for IPv6 literals or malformed input — callers fall back to
/// [`DEFAULT_PORT`].
fn listen_port(listen_address: &str) -> Option<u16> {
    listen_address.rsplit_once(':')?.1.parse().ok()
}

#[cfg(test)]
mod tests {
    use super::*;
    use std::fs;

    #[test]
    fn extracts_port_from_ipv4_listen_address() {
        assert_eq!(listen_port("0.0.0.0:7037"), Some(7037));
        assert_eq!(listen_port("127.0.0.1:8080"), Some(8080));
    }

    #[test]
    fn returns_none_for_unparseable_input() {
        assert_eq!(listen_port("0.0.0.0"), None);
        assert_eq!(listen_port(""), None);
        assert_eq!(listen_port("0.0.0.0:notaport"), None);
    }

    #[test]
    fn dockerfile_for_default_config_uses_default_features() {
        // Default config (didcomm + redis, no explicit secret backend)
        // matches the mediator crate's default features, so the wizard
        // must NOT pass `--no-default-features` — that's what produces
        // the simplest, most cache-friendly Docker build.
        let dir = tempfile::tempdir().unwrap();
        let cfg = WizardConfig::default();
        generate_dockerfile(&cfg, dir.path()).unwrap();

        let dockerfile = fs::read_to_string(dir.path().join("Dockerfile")).unwrap();
        assert!(
            !dockerfile.contains("--no-default-features"),
            "default config shouldn't override default features:\n{dockerfile}"
        );
        assert!(
            dockerfile.contains("cargo build --release --locked -p affinidi-messaging-mediator")
        );
        // The image must build what the lockfile resolved. `COPY . .` brings
        // Cargo.lock in, and the builder tag must not fall behind
        // rust-toolchain.toml or the workspace MSRV refuses the build.
        assert!(dockerfile.contains("FROM rust:1.95-bookworm"));
    }

    #[test]
    fn dockerfile_for_fjall_backend_includes_fjall_feature() {
        // Regression: an earlier `build_features` impl forgot to add
        // the storage backend, so a Fjall wizard run produced a
        // Dockerfile that built a binary with no backend at all.
        let dir = tempfile::tempdir().unwrap();
        let cfg = WizardConfig {
            storage_backend: "fjall".into(),
            ..Default::default()
        };
        generate_dockerfile(&cfg, dir.path()).unwrap();

        let dockerfile = fs::read_to_string(dir.path().join("Dockerfile")).unwrap();
        assert!(
            dockerfile.contains("--no-default-features"),
            "non-default backend choice must override defaults:\n{dockerfile}"
        );
        assert!(
            dockerfile.contains("fjall-backend"),
            "Fjall config must enable fjall-backend feature:\n{dockerfile}"
        );
        assert!(
            !dockerfile.contains("redis-backend"),
            "Fjall config must not enable redis-backend:\n{dockerfile}"
        );
    }

    #[test]
    fn dockerfile_for_redis_with_secret_backend_keeps_redis() {
        // Regression: `redis-backend` is a default feature; when the
        // wizard added a non-default secret backend it triggered
        // `--no-default-features` which silently dropped the storage
        // backend. The fix re-asserts redis-backend explicitly so the
        // binary still has its backend.
        let dir = tempfile::tempdir().unwrap();
        let cfg = WizardConfig {
            secret_storage: "aws_secrets://".into(),
            ..Default::default()
        };
        generate_dockerfile(&cfg, dir.path()).unwrap();

        let dockerfile = fs::read_to_string(dir.path().join("Dockerfile")).unwrap();
        assert!(dockerfile.contains("--no-default-features"));
        assert!(
            dockerfile.contains("redis-backend"),
            "Redis config must explicitly re-enable redis-backend when \
             --no-default-features is in effect:\n{dockerfile}"
        );
        assert!(dockerfile.contains("secrets-aws"));
    }

    #[test]
    fn compose_for_redis_includes_redis_service() {
        let dir = tempfile::tempdir().unwrap();
        let cfg = WizardConfig::default();
        generate_dockerfile(&cfg, dir.path()).unwrap();
        let compose = fs::read_to_string(dir.path().join("docker-compose.yml")).unwrap();
        assert!(compose.contains("redis:"));
        assert!(compose.contains("redis:7-alpine"));
        assert!(compose.contains("DATABASE_URL: redis://redis:6379/"));
    }

    #[test]
    fn compose_for_fjall_skips_redis_service() {
        // Regression: Fjall is single-node; the compose file must NOT
        // bundle a Redis sidecar (would be wasted resources) and must
        // mount a named volume for the LSM data directory so state
        // survives `docker compose down`.
        let dir = tempfile::tempdir().unwrap();
        let cfg = WizardConfig {
            storage_backend: "fjall".into(),
            ..Default::default()
        };
        generate_dockerfile(&cfg, dir.path()).unwrap();
        let compose = fs::read_to_string(dir.path().join("docker-compose.yml")).unwrap();
        assert!(
            !compose.contains("redis:7-alpine"),
            "Fjall compose must not bundle Redis:\n{compose}"
        );
        assert!(compose.contains("mediator-data:"));
    }

    #[test]
    fn paths_follow_the_config_and_secrets_are_mounted_not_copied() {
        let _cwd = crate::cwd_lock();
        let dir = tempfile::tempdir().unwrap();
        let conf = dir.path().join("deploy");
        let outside = dir.path().join("vault").join("keys.json");
        let cfg = WizardConfig {
            config_path: conf.join("prod.toml").to_string_lossy().into_owned(),
            deployment_type: crate::consts::DEPLOYMENT_CONTAINER.into(),
            secret_storage: crate::consts::STORAGE_FILE.into(),
            secret_file_path: outside.to_string_lossy().into_owned(),
            ..Default::default()
        };
        generate_dockerfile(&cfg, &conf).unwrap();
        let dockerfile = fs::read_to_string(conf.join("Dockerfile")).unwrap();
        assert!(
            dockerfile.contains("CMD [\"mediator\", \"-c\", \"/etc/mediator/conf/prod.toml\"]"),
            "{dockerfile}"
        );
        assert!(
            !dockerfile.contains("COPY --from=builder /build/crates"),
            "config / keys must not be copied into the image:\n{dockerfile}"
        );
        let compose = fs::read_to_string(conf.join("docker-compose.yml")).unwrap();
        assert!(compose.contains("- ./:/etc/mediator/conf"), "{compose}");
        assert!(
            compose.contains(&format!(
                "{}:/etc/mediator/secrets/keys.json",
                outside.display()
            )),
            "{compose}"
        );
        // The repository's own ignore file is never written.
        assert!(!conf.join(".dockerignore").exists());
        assert!(conf.join("Dockerfile.dockerignore").exists());
    }

    #[test]
    fn an_existing_different_file_is_not_overwritten() {
        // The compose file names the workspace root found from the current
        // directory; hold it still across the two runs.
        let _cwd = crate::cwd_lock();
        let dir = tempfile::tempdir().unwrap();
        fs::write(dir.path().join("Dockerfile"), "# hand-written\n").unwrap();
        let written = generate_dockerfile(&WizardConfig::default(), dir.path()).unwrap();
        assert_eq!(
            fs::read_to_string(dir.path().join("Dockerfile")).unwrap(),
            "# hand-written\n"
        );
        assert!(dir.path().join("Dockerfile.new").exists());
        assert!(written.contains(&dir.path().join("Dockerfile.new")));
        // Re-running with identical output is a no-op, not another `.new`.
        generate_dockerfile(&WizardConfig::default(), dir.path()).unwrap();
        assert!(!dir.path().join("docker-compose.yml.new").exists());
    }

    #[test]
    fn relative_path_walks_up_and_down() {
        assert_eq!(
            relative_path(Path::new("/a/b/conf"), Path::new("/a")),
            "../.."
        );
        assert_eq!(
            relative_path(Path::new("/a"), Path::new("/a/b/conf/Dockerfile")),
            "b/conf/Dockerfile"
        );
        assert_eq!(relative_path(Path::new("/a"), Path::new("/a")), ".");
    }
}
